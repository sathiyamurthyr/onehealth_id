from fastapi import APIRouter, HTTPException, Query
from typing import Dict, Any, Optional
from backend.app.repositories.sp_views_repository import SPViewsRepository

router = APIRouter(prefix="/network/intelligence", tags=["Network - Intelligence & Cross-Provider Brief"])
repo = SPViewsRepository()

@router.get("/telemetry", response_model=Dict[str, Any])
def get_network_telemetry():
    """
    Returns aggregated network operations intelligence:
    Active providers, facility distribution, active consents, exchange volume, and referral flows.
    """
    return repo.get_network_intelligence_telemetry()

@router.get("/patient-brief/{patient_id}", response_model=Dict[str, Any])
def get_authorized_patient_brief(
    patient_id: str,
    requester_provider_id: str = Query(..., description="ID of the provider requesting the intelligence brief"),
    is_emergency: bool = Query(False, description="Whether this brief is requested under break-glass emergency")
):
    """
    Produces an Authorized Patient Brief synthesized across multi-provider records.
    Strictly adheres to active patient consent grants or audited emergency break-glass protocols.
    AI will never expand the patient's consent scope.
    """
    # 1. Check consent authorization unless emergency
    if not is_emergency:
        auth_check = repo.verify_network_consent_access(
            patient_id=patient_id,
            requester_provider_id=requester_provider_id,
            record_type="ALL_RECORDS"
        )
        if not auth_check["is_authorized"]:
            # Check if at least partial consent is granted
            consult_check = repo.verify_network_consent_access(patient_id, requester_provider_id, "CONSULTATION")
            lab_check = repo.verify_network_consent_access(patient_id, requester_provider_id, "LAB_REPORT")
            rx_check = repo.verify_network_consent_access(patient_id, requester_provider_id, "PRESCRIPTION")
            
            if not (consult_check["is_authorized"] or lab_check["is_authorized"] or rx_check["is_authorized"]):
                raise HTTPException(
                    status_code=403,
                    detail=f"Access denied: No active patient consent granted to {requester_provider_id} for patient {patient_id}."
                )

    # 2. Fetch authorized timeline
    timeline = repo.get_network_unified_patient_timeline(patient_id)
    
    # 3. Categorize into brief
    consultations = [e for e in timeline if e.get("event_type") in ("CONSULTATION", "OPD", "ENCOUNTER")]
    prescriptions = [e for e in timeline if e.get("event_type") in ("PRESCRIPTION", "MEDICATION")]
    labs = [e for e in timeline if e.get("event_type") in ("LAB_REPORT", "LABORATORY", "DIAGNOSTIC")]

    # 4. Synthesize brief
    return {
        "patient_id": patient_id,
        "requester_provider_id": requester_provider_id,
        "is_emergency_access": is_emergency,
        "total_authorized_events": len(timeline),
        "summary": {
            "recent_consultations_count": len(consultations),
            "recent_prescriptions_count": len(prescriptions),
            "recent_diagnostic_investigations_count": len(labs),
            "participating_source_providers": list(set([e.get("source_provider_name") for e in timeline if e.get("source_provider_name")])),
        },
        "authorized_timeline": timeline[:20],
        "provenance_notice": "Generated by OH-ID Network Intelligence Engine. All statements are bound strictly to authorized source provider records."
    }
