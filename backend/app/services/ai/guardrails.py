import re
from typing import List, Tuple

class AIGuardrails:
    """
    Enforces clinical safety constraints, prompt injection filtering, and anti-hallucination guardrails.
    """
    
    INJECTION_PATTERNS = [
        re.compile(r'ignore\s+all\s+previous\s+instructions', re.IGNORECASE),
        re.compile(r'system\s+override', re.IGNORECASE),
        re.compile(r'you\s+are\s+now\s+in\s+dan\s+mode', re.IGNORECASE),
        re.compile(r'bypass\s+rbac', re.IGNORECASE),
        re.compile(r'drop\s+table', re.IGNORECASE),
        re.compile(r'reveal\s+secret\s+keys', re.IGNORECASE),
        re.compile(r'disregard\s+system\s+directive', re.IGNORECASE)
    ]
    
    AUTONOMOUS_PRESCRIPTION_PATTERNS = [
        re.compile(r'i\s+hereby\s+prescribe', re.IGNORECASE),
        re.compile(r'i\s+have\s+ordered\s+the\s+following\s+drugs', re.IGNORECASE),
        re.compile(r'dosage\s+is\s+hereby\s+finalized', re.IGNORECASE)
    ]
    
    @classmethod
    def validate_input(cls, user_prompt: str) -> Tuple[bool, List[str]]:
        flags: List[str] = []
        for pattern in cls.INJECTION_PATTERNS:
            if pattern.search(user_prompt):
                flags.append("POTENTIAL_PROMPT_INJECTION")
                return False, flags
        return True, flags

    @classmethod
    def validate_and_sanitize_output(cls, completion_text: str, is_clinical: bool = True) -> Tuple[str, List[str]]:
        flags: List[str] = []
        out = completion_text
        
        # Check for autonomous clinical claims
        if is_clinical:
            for pattern in cls.AUTONOMOUS_PRESCRIPTION_PATTERNS:
                if pattern.search(out):
                    flags.append("AUTONOMOUS_CLINICAL_CLAIM_DETECTED")
                    out += "\n\n*(Safety Notice: AI cannot autonomously prescribe. This output is strictly draft text for physician evaluation.)*"
            
            # Ensure clinical disclaimer is always present if not already in text
            if "clinician" not in out.lower() and "disclaimer" not in out.lower():
                out += "\n\n*(Notice: Generated by OH-ID Clinical Intelligence. Requires Clinician Sign-Off before medical action.)*"
                
        return out, flags
